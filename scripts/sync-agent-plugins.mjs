import assert from "node:assert/strict";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const apiProtocols = ["openai-chat", "openai-responses", "anthropic", "gemini"];
export const AGENT_PACKAGES = Object.freeze([
  {
    id: "tunnelde-ai",
    title: "Tunnelde AI",
    icon: "bot",
    primaryProtocols: apiProtocols,
    defaultProtocol: "openai-chat",
  },
  {
    id: "tunnelde-codex",
    title: "Codex",
    icon: "terminal",
    primaryProtocols: ["codex"],
    defaultProtocol: "codex",
  },
  {
    id: "tunnelde-claude-code",
    title: "Claude Code",
    icon: "sparkles",
    primaryProtocols: ["claude-code"],
    defaultProtocol: "claude-code",
  },
  {
    id: "tunnelde-pi",
    title: "Pi",
    icon: "message-square",
    primaryProtocols: ["pi"],
    defaultProtocol: "pi",
  },
]);

/** Checked-in runtime copies keep source-folder installation and every ZIP self-contained. */
export async function syncAgentPlugins({ write = false } = {}) {
  const canonical = join(root, "plugins", "tunnelde-ai");
  const libs = (await readdir(join(canonical, "lib")))
    .filter((name) => name.endsWith(".mjs") && name !== "identity.mjs")
    .sort();
  const runtime = [
    "index.mjs",
    "remote-entry.mjs",
    "stdio-entry.mjs",
    ...libs.map((name) => `lib/${name}`),
  ];
  const changed = [];
  for (const agent of AGENT_PACKAGES) {
    const directory = join(root, "plugins", agent.id);
    const identity = `// Generated by scripts/sync-agent-plugins.mjs. Package identity cannot be overridden by configuration.\nexport const PLUGIN_ID = ${JSON.stringify(agent.id)};\nexport const PLUGIN_TITLE = ${JSON.stringify(agent.title)};\nexport const PLUGIN_ICON = ${JSON.stringify(agent.icon)};\nexport const PROFILE_POLICY = Object.freeze({\n  primaryProtocols: Object.freeze(${JSON.stringify(agent.primaryProtocols)}),\n  reviewerProtocols: Object.freeze(${JSON.stringify(apiProtocols)}),\n  defaultProtocol: ${JSON.stringify(agent.defaultProtocol)},\n});\n`;
    const expected = new Map([["lib/identity.mjs", identity]]);
    if (agent.id !== "tunnelde-ai")
      for (const file of runtime)
        expected.set(file, await readFile(join(canonical, file), "utf8"));
    for (const [file, content] of expected) {
      const target = join(directory, file);
      const actual = await readFile(target, "utf8").catch((error) => {
        if (error.code === "ENOENT") return null;
        throw error;
      });
      if (actual === content) continue;
      if (!write)
        throw new Error(
          `${agent.id}/${file}: runtime copy drifted; run npm run agents:sync`,
        );
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, content);
      changed.push(`${agent.id}/${file}`);
    }
    const manifest = JSON.parse(
      await readFile(join(directory, "tunnelde-plugin.json"), "utf8"),
    );
    assert.equal(manifest.id, agent.id);
    assert.equal(manifest.name, agent.title);
    assert.equal(manifest.views?.[0]?.title, agent.title);
    assert.equal(manifest.views?.[0]?.icon, agent.icon);
  }
  return changed;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const changed = await syncAgentPlugins({
    write: process.argv.includes("--write"),
  });
  console.log(
    `Checked ${AGENT_PACKAGES.length} independent assistant packages; updated ${changed.length} runtime files.`,
  );
}
